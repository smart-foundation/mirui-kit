mod capture_png;
use capture_png::write_png;
//! Reproducible fresh-App captures of all routes and real overlay entry flows.
use mirui::{
    prelude::*,
    render::texture::ColorFormat,
    surface::framebuf::FramebufSurface,
};
use std::{
    path::{Path, PathBuf},
};
use studio::{commands::Command, model::StudioHandle};
use studio_core::{Route, Surface};
const WIDTH: u16 = 1400;
const HEIGHT: u16 = 900;
fn main() {
    let mut args = std::env::args().skip(1);
    let output = match args.next().as_deref() {
        None => PathBuf::from("artifacts/studio"),
        Some("--out") => PathBuf::from(args.next().expect("--out needs a directory")),
        _ => panic!("usage: studio-snapshot [--out DIRECTORY]"),
    };
    assert!(args.next().is_none(), "unexpected argument");
    std::fs::create_dir_all(&output).expect("snapshot directory");
    for (index, route) in Route::ALL.into_iter().enumerate() {
        capture(
            &output,
            &format!("s{:02}-{}.png", index + 1, route.title().to_lowercase()),
            route,
            None,
            false,
        );
    }
    for (index, surface) in Surface::ALL.into_iter().enumerate() {
        let route = match surface {
            Surface::Inspector
            | Surface::Context
            | Surface::Options
            | Surface::AssetPreview
            | Surface::Move => Route::Collections,
            Surface::Conflict => Route::Controls,
            Surface::Unsaved => Route::Workbench,
            Surface::Recovery => Route::Foundations,
            _ => Route::Surfaces,
        };
        capture(
            &output,
            &format!("o{:02}.png", index + 1),
            route,
            Some(surface),
            false,
        );
    }
    capture(
        &output,
        "light-foundations.png",
        Route::Foundations,
        None,
        true,
    );
    std::fs::write(output.join("README.txt"),"Fresh RGBA captures, generated by studio-snapshot. Images are evidence to review, not automatic visual approval. 6 routes + 17 surfaces + light appearance. See docs/showcase/IMPLEMENTATION.md for limits.\n").expect("capture index");
}
fn press(state: &StudioHandle, command: Command) {
    state.execute(command as u16);
}
fn capture(output: &Path, name: &str, route: Route, surface: Option<Surface>, light: bool) {
    let backend = FramebufSurface::with_format(WIDTH, HEIGHT, ColorFormat::RGBA8888, |_, _| {});
    let mut app = App::new(backend);
    app.with_default_widgets().with_default_systems();
    let state = studio::install(&mut app);
    state.execute(route as u16 + 1);
    state.sync();
    if light {
        press(&state, Command::Light);
        press(&state, Command::ApplyAppearance);
        press(&state, Command::Keep);
    }
    if let Some(surface) = surface {
        match surface {
            Surface::Inspector | Surface::Context | Surface::AssetPreview | Surface::Move => {
                state.execute(1003);
                state.execute(3000 + surface as u16);
            }
            Surface::Conflict => {
                press(&state, Command::SavePreset);
                press(&state, Command::SavePreset);
            }
            Surface::Unsaved => {
                state
                    .note()
                    .set_text("Unsaved note fixture")
                    .expect("note fixture fits");
                state.sync();
                press(&state, Command::Overview);
            }
            Surface::Recovery => {
                press(&state, Command::Light);
                press(&state, Command::ApplyAppearance);
            }
            _ => state.execute(3000 + surface as u16),
        }
        assert_eq!(
            state.surface(),
            Some(surface),
            "capture flow did not enter the requested surface"
        );
    }
    // render/snapshot do not advance systems upstream. Settle input gates,
    // field metrics and focus before capturing any visual evidence.
    app.tick();
    app.tick();
    app.render().expect("snapshot layout and frame");
    app.render().expect("snapshot settled frame");
    let texture = app
        .snapshot()
        .expect("snapshot readback")
        .expect("a rendered frame");
    let pixels = texture.read_pixels().expect("CPU-readable pixels");
    write_png(&output.join(name), &pixels);
    println!("{}", output.join(name).display());
}
